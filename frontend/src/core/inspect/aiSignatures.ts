import { msg, raw, type Msg } from '../../types';

/**
 * Dấu hiệu nhận biết công cụ / chuẩn đánh dấu ảnh AI xuất hiện dưới dạng văn bản trong metadata.
 * Chỉ dùng cụm từ đặc trưng để hạn chế nhận diện nhầm. Tên công cụ là tên riêng nên không cần dịch.
 */
const SIGNATURES: [RegExp, Msg][] = [
  [/trainedAlgorithmicMedia|compositeWithTrainedAlgorithmicMedia/i, msg('sigIptcAi')],
  [/\balgorithmicMedia\b/i, msg('sigIptcAlgo')],
  [/midjourney/i, raw('Midjourney')],
  [/dall[-·∙ ]?e/i, raw('DALL·E (OpenAI)')],
  [/\bopenai\b|chatgpt|gpt-4o|\bsora\b/i, raw('OpenAI')],
  [/stable[ -]?diffusion|\bsdxl\b|automatic1111|stable-diffusion-webui/i, raw('Stable Diffusion')],
  [/negative prompt:|\bsteps: ?\d+, ?sampler:/i, msg('sigSdParams')],
  [/comfyui|"class_type"\s*:/i, raw('ComfyUI')],
  [/novelai/i, raw('NovelAI')],
  [/invokeai/i, raw('InvokeAI')],
  [/adobe firefly|\bfirefly\b|generative fill|generative expand/i, raw('Adobe Firefly / Generative Fill')],
  [/\bimagen\b|gemini|google ai/i, raw('Google Imagen / Gemini')],
  [/meta ai|imagine with meta|imagined with ai/i, raw('Meta AI')],
  [/leonardo\.ai|leonardo ai/i, raw('Leonardo.Ai')],
  [/ideogram/i, raw('Ideogram')],
  [/\bflux\.1\b|black forest labs/i, raw('FLUX (Black Forest Labs)')],
  [/bing image creator|microsoft designer/i, raw('Microsoft Designer / Bing Image Creator')],
  [/made with ai|ai[- ]generated|generated by ai|created with ai/i, msg('sigAiLabel')],
];

export function aiSignature(text: string): Msg | null {
  if (!text) return null;
  const sample = text.length > 200_000 ? text.slice(0, 200_000) : text;
  for (const [re, label] of SIGNATURES) if (re.test(sample)) return label;
  return null;
}

